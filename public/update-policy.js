export const RELEASE_API = 'https://api.github.com/repos/ChrisLu7899/NIKKE-Workshop/releases/latest';
export const RELEASE_ROOT = 'https://github.com/ChrisLu7899/NIKKE-Workshop/releases/';
export const UPDATE_KEY = 'workshop.update.v1';
export const UPDATER_URI = 'nikke-workshop://update';
export const CHECK_INTERVAL = 24 * 60 * 60 * 1000;
export function versionParts(value) {
  if (!/^v?\d+(?:\.\d+){2,3}$/.test(String(value))) throw new Error('版本号格式不受支持');
  const parts = String(value).replace(/^v/, '').split('.').map(Number);
  if (parts.some((part) => !Number.isSafeInteger(part) || part > 65535)) throw new Error('版本号超出范围');
  return [...parts, ...Array(4 - parts.length).fill(0)];
}
export function compareVersions(a, b) {
  const left = versionParts(a), right = versionParts(b);
  for (let i = 0; i < 4; i++) if (left[i] !== right[i]) return Math.sign(left[i] - right[i]);
  return 0;
}
export function parseRelease(raw) {
  if (!raw || raw.draft || raw.prerelease) throw new Error('没有可用的稳定版本');
  versionParts(raw.tag_name);
  const version = raw.tag_name.replace(/^v/, '');
  const url = `${RELEASE_ROOT}tag/${raw.tag_name}`;
  if (raw.html_url !== url) throw new Error('发布来源不匹配');
  const candidates = (raw.assets || []).filter((a) => a.name === 'NIKKE-Workshop.zip' || a.name === `NIKKE-Workshop-${raw.tag_name}.zip` || a.name === `NIKKE-Workshop-${version}.zip`);
  // Never choose source ZIPs or GitHub's autogenerated source archives.
  const item = candidates.find((a) => a.name === 'NIKKE-Workshop.zip') || candidates[0];
  let asset = null;
  if (item) {
    const expected = `${RELEASE_ROOT}download/${raw.tag_name}/${item.name}`;
    if (item.browser_download_url !== expected || !Number.isSafeInteger(item.id) || item.id <= 0 || !Number.isSafeInteger(item.size) || item.size <= 0 || item.size > 8 * 1024 ** 3) throw new Error('安装包来源或大小不合法');
    asset = { id: item.id, name: item.name, size: item.size, url: expected, digest: /^sha256:[a-f0-9]{64}$/i.test(item.digest || '') ? item.digest.toLowerCase() : null };
  }
  return { version, tag: raw.tag_name, url, publishedAt: Number.isFinite(Date.parse(raw.published_at)) ? raw.published_at : null, notes: String(raw.body || '').slice(0, 30000), asset };
}
